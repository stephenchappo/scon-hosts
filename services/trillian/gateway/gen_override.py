#!/usr/bin/env python3
"""Write compose.override.yaml: one ${NAME:?} line per secret the tables name.

compose passes only variables it is told about, so every token verifier and tool
credential named in tokens.yaml and tools.yaml gets a line here. Names only, never
values; the values come from bws-run at start. The file is generated, so it's gitignored.

    python3 gen_override.py /path/to/scon-system/gateway > compose.override.yaml
"""
import sys, pathlib, yaml

d = pathlib.Path(sys.argv[1])
names = set()
for t in (yaml.safe_load((d / "tokens.yaml").read_text()) or {}).get("tokens") or []:
    names.add("GW_TOKEN_SHA256_" + t["id"].upper().replace("-", "_"))
for a in (yaml.safe_load((d / "tools.yaml").read_text()) or {}).get("accounts") or []:
    names.add(a["auth"]["secret"])
env = {n: "${%s:?missing from Secrets Manager project gateway}" % n for n in sorted(names)}
print("# Generated by gen_override.py from the gateway tables. Do not edit.")
print(yaml.safe_dump({"services": {"gateway": {"environment": env}}} if env else {"services": {"gateway": {}}}, sort_keys=True), end="")
